"""Kemendagri administrative region codes (provinsi / kab-kota / kecamatan).

Data is bundled in ``kawallm/data/wilayah_kemendagri.json``, generated by
``scripts/build_wilayah.py`` from https://github.com/cahyadsn/wilayah (MIT).
It is the *union* of the 2016–2025 Kepmendagri decrees, because a NIK keeps the
kecamatan code that was valid when it was issued even after pemekaran.
"""

from __future__ import annotations

import json
from functools import lru_cache
from importlib import resources


@lru_cache(maxsize=1)
def _load() -> dict:
    with resources.files("kawallm.data").joinpath("wilayah_kemendagri.json").open(encoding="utf-8") as f:
        return json.load(f)


@lru_cache(maxsize=1)
def kecamatan_codes() -> frozenset[str]:
    return frozenset(_load()["kecamatan"])


def is_valid_kecamatan(code6: str) -> bool:
    return code6 in kecamatan_codes()


def lookup(code6: str) -> dict[str, str | None]:
    """Return province / regency / district names for a 6-digit code."""
    d = _load()
    return {
        "provinsi": d["provinsi"].get(code6[:2]),
        "kabkota": d["kabkota"].get(code6[:4]),
        "kecamatan": d["kecamatan"].get(code6),
    }
